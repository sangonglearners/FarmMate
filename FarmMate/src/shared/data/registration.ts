// 작물 검색 함수
export function searchCrops(searchTerm: string): RegistrationData[] {
  console.log('🔍 searchCrops 함수 호출:', searchTerm);
  
  if (!searchTerm.trim()) {
    console.log('❌ 검색어가 비어있음');
    return [];
  }

  const term = searchTerm.toLowerCase();
  console.log('🔍 검색어 (소문자):', term);
  
  const results = registrationData.filter(crop => {
    const 품목매치 = crop.품목.toLowerCase().includes(term);
    const 대분류매치 = crop.대분류.toLowerCase().includes(term);
    const 품종매치 = crop.품종.toLowerCase().includes(term);
    
    console.log(`🔍 ${crop.품목} 검사:`, {
      품목: crop.품목,
      품목매치,
      대분류: crop.대분류,
      대분류매치,
      품종: crop.품종,
      품종매치,
      최종결과: 품목매치 || 대분류매치 || 품종매치
    });
    
    return 품목매치 || 대분류매치 || 품종매치;
  });
  
  console.log('✅ 검색 결과:', results);
  return results;
}

// 대분류별 작물 조회
export function getCropsByCategory(category: string): RegistrationData[] {
  return registrationData.filter(crop => crop.대분류 === category);
}

// 모든 대분류 목록 조회
export function getCategories(): string[] {
  const categories = Array.from(new Set(registrationData.map(crop => crop.대분류)));
  return categories.sort();
}

// 특정 작물 정보 조회
export function getCropById(id: string): RegistrationData | undefined {
  return registrationData.find(crop => crop.id === id);
}